/**
 * 标签定义默认使用同名工厂；遇到 JS 关键字或节点方法冲突时声明别名。
 */
function normalizeElementDefinition(definition) {
  if (typeof definition === 'string') {
    return {
      name: definition,
      tagName: definition
    };
  }

  return definition;
}
